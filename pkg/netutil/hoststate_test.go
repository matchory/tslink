// parseSave reads the chains of a table and the rules of each, in order, as
// iptables-save prints them; comments, policies and counters are not rules.
func TestParseSave(t *testing.T) {
	out := `# Generated by iptables-save v1.8.10 (nf_tables) on Tue Oct 13 12:00:00 2026
*mangle
:PREROUTING ACCEPT [12:3456]
:FORWARD ACCEPT [0:0]
:TSLINK-VETH-FWD - [0:0]
-A FORWARD -j TSLINK-VETH-FWD
-A FORWARD -i dummy0 -j ACCEPT
-A TSLINK-VETH-FWD -d 10.200.0.0/16 -m comment --comment "a b" -j DROP
COMMIT
# Completed on Tue Oct 13 12:00:00 2026
`
	got := parseSave(out)
	wantChains := map[string]bool{"PREROUTING": true, "FORWARD": true, "TSLINK-VETH-FWD": true}
	if !maps.Equal(got.chains, wantChains) {
		t.Errorf("chains = %v, want %v", got.chains, wantChains)
	}
	wantRules := map[string][]string{
		"FORWARD": {"-A FORWARD -j TSLINK-VETH-FWD", "-A FORWARD -i dummy0 -j ACCEPT"},
		"TSLINK-VETH-FWD": {
			`-A TSLINK-VETH-FWD -d 10.200.0.0/16 -m comment --comment "a b" -j DROP`,
		},
	}
	if !maps.EqualFunc(got.rules, wantRules, slices.Equal) {
		t.Errorf("rules = %q, want %q", got.rules, wantRules)
	}
	if got := parseSave(""); len(got.chains) != 0 || len(got.rules) != 0 {
		t.Errorf("empty output: %+v", got)
	}
}

// A chain's lines hold its rules only if both are what was remembered.
func TestCheckedChainHolds(t *testing.T) {
	rules := [][]string{{"-j", "DROP"}}
	c := checkedChain{lines: []string{"-A C -j DROP"}, rules: rules}
	if !c.holds([]string{"-A C -j DROP"}, [][]string{{"-j", "DROP"}}) {
		t.Error("the remembered lines and rules do not hold")
	}
	if c.holds([]string{"-A C -j DROP", "-A C -j ACCEPT"}, rules) {
		t.Error("other lines hold")
	}
	if c.holds([]string{"-A C -j DROP"}, [][]string{{"-j", "ACCEPT"}}) {
		t.Error("the lines hold other rules")
	}
}
