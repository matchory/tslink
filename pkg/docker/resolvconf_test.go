package docker

import (
	"net/netip"
	"slices"
	"testing"
)

// The comments as Docker writes them in a container's resolv.conf
// (libnetwork/internal/resolvconf, Generate).
const (
	resolvConfHeader = `# Generated by Docker Engine.
# This file can be edited; Docker Engine will not make further changes once it
# has been modified.

nameserver 127.0.0.11
options ndots:0

`
	// With daemon.json {"dns": ["10.0.0.2", "1.1.1.1"]}, or --dns.
	daemonDNSResolvConf = resolvConfHeader + `# Based on host file: '/etc/resolv.conf' (internal resolver)
# ExtServers: [10.0.0.2 1.1.1.1]
# Overrides: [nameservers]
# Option ndots from: internal
`
	// With no DNS configured: the host's servers.
	hostDNSResolvConf = resolvConfHeader + `# Based on host file: '/run/systemd/resolve/resolv.conf' (internal resolver)
# ExtServers: [host(10.0.0.53) host(192.168.1.1)]
# Overrides: []
# Option ndots from: internal
`
)

func TestConfiguredDNS(t *testing.T) {
	for _, tt := range []struct {
		name, conf string
		want       []netip.Addr
	}{
		{
			"daemon.json servers",
			daemonDNSResolvConf,
			[]netip.Addr{netip.MustParseAddr("10.0.0.2"), netip.MustParseAddr("1.1.1.1")},
		},
		{
			"with search override too",
			resolvConfHeader + "# ExtServers: [fd00::53]\n# Overrides: [nameservers search]\n",
			[]netip.Addr{netip.MustParseAddr("fd00::53")},
		},
		{"the host's servers", hostDNSResolvConf, nil},
		{
			"search override only",
			resolvConfHeader + "# ExtServers: [host(10.0.0.53)]\n# Overrides: [search]\n",
			nil,
		},
		{"rewritten by the container", "nameserver 9.9.9.9\n", nil},
		{"no ExtServers", resolvConfHeader + "# Overrides: [nameservers]\n", nil},
		{
			"invalid entries dropped",
			resolvConfHeader + "# ExtServers: [x 10.0.0.2 host(]\n# Overrides: [nameservers]\n",
			[]netip.Addr{netip.MustParseAddr("10.0.0.2")},
		},
		{"unbracketed", "# ExtServers: 10.0.0.2\n# Overrides: [nameservers]\n", nil},
	} {
		t.Run(tt.name, func(t *testing.T) {
			if got := configuredDNS([]byte(tt.conf)); !slices.Equal(got, tt.want) {
				t.Errorf("configuredDNS = %v, want %v", got, tt.want)
			}
		})
	}
}

// A container without DNS servers of its own gets daemon.json's, from its
// resolv.conf; one with its own does not have that read.
func TestEventStartsTailscaleWithDaemonDNS(t *testing.T) {
	s := newEventSetup(t, true)
	s.td.fake.setResolvConf(s.containerID, daemonDNSResolvConf)
	s.td.fake.send(t, connectEvent(s.netID, "billing_net", s.containerID))
	receive(t, s.handled, "the connect event")
	want := []netip.Addr{netip.MustParseAddr("10.0.0.2"), netip.MustParseAddr("1.1.1.1")}
	if r := s.td.nextRun(t); !slices.Equal(r.info.DNS, want) {
		t.Errorf("started Tailscale with DNS %v, want %v", r.info.DNS, want)
	}

	s = newEventSetup(t, true)
	own := netip.MustParseAddr("9.9.9.9")
	s.td.fake.setDNS(s.containerID, own)
	s.td.fake.setResolvConf(s.containerID, daemonDNSResolvConf)
	s.td.fake.send(t, connectEvent(s.netID, "billing_net", s.containerID))
	receive(t, s.handled, "the connect event")
	if r := s.td.nextRun(t); !slices.Equal(r.info.DNS, []netip.Addr{own}) {
		t.Errorf("started Tailscale with DNS %v, want the container's own", r.info.DNS)
	}
	s.td.fake.mu.Lock()
	defer s.td.fake.mu.Unlock()
	if s.td.fake.copies != 0 {
		t.Errorf("read the resolv.conf of a container with its own DNS servers")
	}
}

// Without a readable resolv.conf, the container has no DNS servers, as
// before: tailscaled uses the host's.
func TestEventWithoutResolvConf(t *testing.T) {
	s := newEventSetup(t, true)
	s.td.fake.send(t, connectEvent(s.netID, "billing_net", s.containerID))
	receive(t, s.handled, "the connect event")
	if r := s.td.nextRun(t); len(r.info.DNS) != 0 {
		t.Errorf("started Tailscale with DNS %v, want none", r.info.DNS)
	}
}
